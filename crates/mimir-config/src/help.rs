//! `-help` / `-help-all` output.
//!
//! Ported from:
//! - github.com/grafana/mimir/pkg/util/usage/usage.go (`Usage`)
//! - github.com/grafana/mimir/pkg/util/configdoc/{hidden,fieldcategory}.go
//! - github.com/grafana/mimir/cmd/mimir/help.txt.tmpl, help-all.txt.tmpl (data)
//!
//! Go renders each flag from reflection over `mimir.Config` (struct `category`/`doc` tags,
//! category and hidden overrides, `flag.Getter` type names, `doc:"default=..."` overrides).
//! The result depends only on the build (`DefValue` is captured at flag registration, before
//! the config file and CLI flags are applied), and upstream checks it in as
//! `cmd/mimir/help.txt.tmpl` (basic flags) and `cmd/mimir/help-all.txt.tmpl` (all flags),
//! regenerated by `make doc` (`mimir -h` / `mimir -help-all`) and asserted by upstream tests.
//! Those two files are vendored verbatim under `src/help/` and are the per-flag source of
//! truth for category filtering, `[experimental]`/`[deprecated]` markers, hidden flags, type
//! names, usage strings and default rendering.
//!
//! Regenerate after bumping `.ref/mimir`:
//! `cp .ref/mimir/cmd/mimir/help.txt.tmpl .ref/mimir/cmd/mimir/help-all.txt.tmpl crates/mimir-config/src/help/`
//! (`help_templates_match_upstream` fails when they drift from `.ref/mimir`).

static HELP_BASIC: &str = include_str!("help/help.txt.tmpl");
static HELP_ALL: &str = include_str!("help/help-all.txt.tmpl");

/// Footer printed by `usage.Usage` when only basic flags are shown.
const HELP_ALL_HINT: &str = "\nTo see all flags, use -help-all\n";

/// Splits a rendered usage template into `(flag name, rendered block)` pairs, in order.
/// Each block is the `  -name [type]` line plus its `    \t...` usage lines, newline-terminated.
fn entries(tmpl: &'static str) -> Vec<(&'static str, &'static str)> {
    let mut out = Vec::new();
    let mut start: Option<(usize, &'static str)> = None;
    let mut offset = 0;
    for line in tmpl.split_inclusive('\n') {
        let is_continuation = line.starts_with("    \t");
        if !is_continuation {
            if let Some((s, name)) = start.take() {
                out.push((name, &tmpl[s..offset]));
            }
            if let Some(rest) = line.strip_prefix("  -") {
                let name = rest
                    .trim_end_matches('\n')
                    .split(' ')
                    .next()
                    .unwrap_or_default();
                start = Some((offset, name));
            }
        }
        offset += line.len();
    }
    if let Some((s, name)) = start {
        out.push((name, &tmpl[s..offset]));
    }
    out
}

/// Renders `usage.Usage(printAll, ...)` for the flags accepted by this binary (`is_registered`).
/// Flags Go hides (`doc:"hidden"`, hidden overrides, `deprecated` placeholders) are absent from
/// the templates and therefore never printed.
pub fn format_usage(prog_name: &str, print_all: bool, is_registered: impl Fn(&str) -> bool) -> String {
    let tmpl = if print_all { HELP_ALL } else { HELP_BASIC };
    let mut out = format!("Usage of {prog_name}:\n");
    for (name, block) in entries(tmpl) {
        if is_registered(name) {
            out.push_str(block);
        }
    }
    if !print_all {
        out.push_str(HELP_ALL_HINT);
    }
    out
}

/// Every flag name documented by Go `-help-all` (basic, advanced, experimental, deprecated).
pub fn documented_flag_names() -> Vec<&'static str> {
    entries(HELP_ALL).into_iter().map(|(n, _)| n).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn strip_usage_line(s: &str) -> &str {
        &s[s.find('\n').unwrap() + 1..]
    }

    #[test]
    fn renders_templates_verbatim_when_everything_is_registered() {
        for (all, tmpl) in [(false, HELP_BASIC), (true, HELP_ALL)] {
            let out = format_usage("./cmd/mimir/mimir", all, |_| true);
            assert_eq!(out, tmpl);
        }
    }

    #[test]
    fn skips_unregistered_flags() {
        let out = format_usage("mimir", false, |n| n == "version" || n == "target");
        assert_eq!(
            out,
            "Usage of mimir:\n  -target comma-separated-list-of-strings\n    \tComma-separated list of components to include in the instantiated process. The default value 'all' includes all components that are required to form a functional Grafana Mimir instance in single-binary mode. Use the '-modules' command line flag to get a list of available components, and to see which components are included with 'all'. (default all)\n  -version\n    \tPrint application version and exit.\n\nTo see all flags, use -help-all\n"
        );
    }

    #[test]
    fn categories_and_markers() {
        let basic: Vec<_> = entries(HELP_BASIC).into_iter().map(|(n, _)| n).collect();
        let all = entries(HELP_ALL);
        assert!(basic.len() < all.len());
        assert!(basic.contains(&"ingester.ring.replication-factor"));
        assert!(!basic.contains(&"ingester.ring.num-tokens"));
        // Hidden in Go (configdoc hidden overrides / doc:"hidden").
        for hidden in ["server.grpc.recv-buffer-pools-enabled", "ingester.push-grpc-method-enabled", "compartments.enabled"] {
            assert!(!all.iter().any(|(n, _)| *n == hidden), "{hidden}");
        }
        assert!(all.iter().any(|(_, b)| b.contains("\t[experimental] ")));
        assert!(all.iter().any(|(_, b)| b.contains("\t[deprecated] ")));
    }

    // Keeps the vendored templates in sync with the upstream reference checkout.
    #[test]
    fn help_templates_match_upstream() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.ref/mimir/cmd/mimir");
        for (file, vendored) in [("help.txt.tmpl", HELP_BASIC), ("help-all.txt.tmpl", HELP_ALL)] {
            let Ok(upstream) = std::fs::read_to_string(root.join(file)) else {
                eprintln!("skipping: .ref/mimir not available");
                return;
            };
            assert_eq!(strip_usage_line(&upstream), strip_usage_line(vendored), "{file} drifted from .ref/mimir");
        }
    }
}
